"""Validate explicit Roblox upload IDs; optionally write the runtime bindings."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("mapping", type=Path)
parser.add_argument("--write", action="store_true", help="Write src/shared/ContentIds.luau after validation")
args = parser.parse_args()
mapping = json.loads(args.mapping.read_text(encoding="utf-8"))
manifest = json.loads((ROOT / "assets/production/upload-manifest.json").read_text())
allowed = {"Audio": {i["key"] for i in manifest["audio"]}, "Images": {i["key"] for i in manifest["images"]}}
if set(mapping) - set(allowed):
    parser.error("Only Audio and Images top-level keys are accepted")
lines = ["-- Real upload IDs supplied by the experience owner. Generated by tools/configure_content.py.", "return {"]
for section in ("Audio", "Images"):
    values = mapping.get(section, {})
    if not isinstance(values, dict): parser.error(section + " must be an object")
    lines.append("    " + section + " = {")
    for key, value in sorted(values.items()):
        if key not in allowed[section]: parser.error("Unknown content key: " + key)
        if type(value) is not int or not 0 < value < 2 ** 53: parser.error("Asset IDs must be positive integers: " + key)
        lines.append(f"        [{json.dumps(key)}] = {value},")
    lines.append("    },")
lines.append("}")
if args.write:
    (ROOT / "src/shared/ContentIds.luau").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(json.dumps({"validated_audio": len(mapping.get("Audio", {})), "validated_images": len(mapping.get("Images", {})), "runtime_bindings_written": args.write}))
