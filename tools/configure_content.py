"""Merge explicit Roblox upload IDs without discarding existing bindings.

Offline validation is the default. --write updates the canonical JSON and its
Luau projection; neither mode uploads assets or proves experience permissions.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ("Audio", "Images")
HEADER = "-- Real upload IDs supplied by the experience owner. Generated by tools/configure_content.py."


def unique_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def read_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8-sig"), object_pairs_hook=unique_object)


def manifest_keys(manifest: object) -> dict[str, set[str]]:
    if not isinstance(manifest, dict):
        raise ValueError("The upload manifest must be an object")
    allowed = {}
    for section in SECTIONS:
        entries = manifest.get(section.lower())
        if not isinstance(entries, list):
            raise ValueError(f"Manifest {section.lower()} must be an array")
        keys = set()
        for entry in entries:
            key = entry.get("key") if isinstance(entry, dict) else None
            if not isinstance(key, str) or not key or key in keys:
                raise ValueError(f"Invalid or duplicate manifest key in {section}: {key!r}")
            # Keys are emitted as Luau string literals; the current contract is ASCII.
            if any(c not in "abcdefghijklmnopqrstuvwxyz0123456789_." for c in key):
                raise ValueError(f"Unsupported manifest key: {key!r}")
            keys.add(key)
        allowed[section] = keys
    return allowed


def allowed_content_keys() -> dict[str, set[str]]:
    from active_content import active_audio
    allowed = manifest_keys(read_json(ROOT / "assets/production/upload-manifest.json"))
    # Historical manifests never grant an audio key. Inactive bindings cannot
    # survive merge semantics or return through an incremental configuration.
    allowed["Audio"] = set(active_audio())
    return allowed


def validate_mapping(mapping: object, allowed: dict[str, set[str]]) -> dict[str, dict[str, int]]:
    if not isinstance(mapping, dict):
        raise ValueError("A content mapping must be an object containing Audio and/or Images")
    unknown = set(mapping) - set(SECTIONS)
    if unknown:
        raise ValueError("Unknown mapping sections: " + ", ".join(sorted(unknown)))
    result = {}
    for section in SECTIONS:
        values = mapping.get(section, {})
        if not isinstance(values, dict):
            raise ValueError(f"{section} must be an object")
        for key, value in values.items():
            if key not in allowed[section]:
                raise ValueError(f"Unknown content key: {section}.{key}")
            if type(value) is not int or not 0 < value < 2 ** 53:
                raise ValueError(f"Asset IDs must be positive exact integers below 2^53: {section}.{key}")
        result[section] = dict(values)
    return result


def merge_mapping(base: dict, incoming: dict, allow_rebind: bool) -> tuple[dict, dict]:
    merged = {section: dict(base[section]) for section in SECTIONS}
    changes = {"added": [], "rebound": [], "unchanged": []}
    for section in SECTIONS:
        for key, value in sorted(incoming[section].items()):
            previous = base[section].get(key)
            name = f"{section}.{key}"
            if previous is not None and previous != value and not allow_rebind:
                raise ValueError(f"Refusing to rebind {name}; review the receipt and use --allow-rebind")
            category = "added" if previous is None else "unchanged" if previous == value else "rebound"
            changes[category].append(name)
            merged[section][key] = value
    return merged, changes


def render_luau(mapping: dict) -> str:
    lines = [HEADER, "return {"]
    for section in SECTIONS:
        if not mapping[section]:
            lines.append(f"    {section} = {{}},")
            continue
        lines.append(f"    {section} = {{")
        for key, value in sorted(mapping[section].items()):
            lines.append(f"        [{json.dumps(key)}] = {value},")
        lines.append("    },")
    return "\n".join(lines + ["}", ""])


def write_bindings(canonical: Path, runtime: Path, mapping: dict, originals: dict) -> None:
    # Stage BOTH complete files before replacing either. Each replace is atomic,
    # not a multi-file transaction. Canonical JSON remains the recovery authority.
    content = {
        canonical: (json.dumps(mapping, indent=2, sort_keys=True) + "\n").encode("utf-8"),
        runtime: render_luau(mapping).encode("utf-8"),
    }
    staged = {}
    canonical_saved = False
    try:
        for path, data in content.items():
            with tempfile.NamedTemporaryFile(prefix=f".{path.name}.", suffix=".tmp",
                                             dir=path.parent, delete=False) as handle:
                staged[path] = Path(handle.name)
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
        for path, original in originals.items():
            current = path.read_bytes() if path.exists() else None
            if current != original:
                raise ValueError(f"{path.name} changed while preparing bindings; rerun after reviewing it")
        os.replace(staged[canonical], canonical)
        canonical_saved = True
        os.replace(staged[runtime], runtime)
    except OSError as exc:
        if canonical_saved:
            raise OSError(
                "Canonical IDs were saved, but the runtime file was not updated. "
                "Resolve the filesystem error, then rerun with data/content-ids.json --write."
            ) from exc
        raise
    finally:
        for path in staged.values():
            path.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mapping", type=Path, help="Full mapping or incremental Audio/Images JSON")
    parser.add_argument("--write", action="store_true", help="Merge into canonical JSON and regenerate Luau")
    parser.add_argument("--allow-rebind", action="store_true", help="Explicitly allow replacing existing IDs")
    args = parser.parse_args(argv)
    canonical = ROOT / "data/content-ids.json"
    runtime = ROOT / "src/shared/ContentIds.luau"
    try:
        originals = {p: p.read_bytes() if p.exists() else None for p in (canonical, runtime)}
        if originals[canonical] is None:
            raise ValueError("Canonical data/content-ids.json is missing; restore it before merging")
        allowed = allowed_content_keys()
        base_data = json.loads(originals[canonical].decode("utf-8-sig"), object_pairs_hook=unique_object)
        if not isinstance(base_data, dict) or set(base_data) != set(SECTIONS):
            raise ValueError("Canonical content-ids.json must explicitly contain Audio and Images")
        retired_audio = sorted(set(base_data["Audio"]) - allowed["Audio"])
        base_data["Audio"] = {key: value for key, value in base_data["Audio"].items() if key in allowed["Audio"]}
        base = validate_mapping(base_data, allowed)
        incoming = validate_mapping(read_json(args.mapping), allowed)
        merged, changes = merge_mapping(base, incoming, args.allow_rebind)
        if args.write:
            write_bindings(canonical, runtime, merged, originals)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    print(json.dumps({
        "mode": "merge", "validated_audio": len(merged["Audio"]),
        "validated_images": len(merged["Images"]), "changes": changes,
        "unbound": {s: sorted(allowed[s] - set(merged[s])) for s in SECTIONS},
        "canonical_mapping_written": args.write, "runtime_bindings_written": args.write,
        "permissions_verified": False,
        "retired_audio_removed": retired_audio,
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
