"""Regenerate music metadata/bindings from explicit admission; no historical auto-admission."""
import json
from active_content import ROOT, active_audio, load_authority, preview_audio


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def lua_json(path, value, header):
    payload = json.dumps(value, separators=(",", ":"), ensure_ascii=True)
    if "]=]" in payload:
        raise ValueError("Invalid Luau JSON delimiter")
    path.write_text("-- " + header + "\nreturn game:GetService(\"HttpService\"):JSONDecode([=[" + payload + "]=])\n", encoding="utf-8")


def project():
    authority = load_authority()
    audio = active_audio()
    plan = json.loads((ROOT / authority["planned_contract"]).read_text(encoding="utf-8"))
    admitted = {identity: row for identity, row in audio.items() if row.get("runtime_admitted") is True}
    previews = preview_audio()
    local_roles = json.loads((ROOT / "data/studio-local-music-roles.v1.json").read_text(encoding="utf-8"))
    lua_json(ROOT / "src/shared/StudioLocalMusicRoles.luau", local_roles,
             "Generated by tools/project_active_content.py; explicit Studio-only gameplay substitutes, never approved discovery recordings.")
    lua_json(ROOT / "src/shared/FirstPackSlots.luau", {"packId": plan["pack_id"], "slots": plan["slots"],
             "banks": plan["banks"], "mappingRevision": plan["mapping_revision"],
             "roleBindings": plan["role_bindings"], "discoveryRoleBindings": plan["discovery_role_bindings"],
             "admitted": admitted, "previews": previews},
             "Generated by tools/project_active_content.py; planning metadata does not grant audio readiness.")
    retired = json.loads((ROOT / authority["retired_catalog"]).read_text(encoding="utf-8"))
    lua_json(ROOT / "src/shared/RetiredSamples.luau", retired["samples"], "Historical IDs for recovery only. Never selectable or playable.")
    (ROOT / "src/shared/StylePacks.luau").write_text("-- Retired. Historical style sources remain archived; no active style kits.\nreturn {}\n", encoding="utf-8")
    for relative in ("data/content-ids.json", "data/content-ids.example.json"):
        path = ROOT / relative
        mapping = json.loads(path.read_text(encoding="utf-8"))
        mapping["Audio"] = {key: value for key, value in mapping["Audio"].items() if key in audio}
        write_json(path, mapping)
    from configure_content import render_luau
    mapping = json.loads((ROOT / "data/content-ids.json").read_text(encoding="utf-8"))
    (ROOT / "src/shared/ContentIds.luau").write_text(render_luau(mapping), encoding="utf-8")
    for relative in ("assets/production/upload-manifest.json", "data/style-upload-manifest.json"):
        path = ROOT / relative
        upload = json.loads(path.read_text(encoding="utf-8"))
        upload["audio"] = [{"key": key, "file": row["file"], "source_sha256": row["sha256"],
                             "asset_id": mapping["Audio"].get(key)} for key, row in sorted(audio.items())]
        upload["active_content_authority"] = "data/active-content.json"
        upload["historical_music_retired"] = True
        write_json(path, upload)
    print(json.dumps({"planned_slots": len(plan["slots"]), "active_musical_samples": len(admitted), "local_personal_previews": len(previews),
                      "retired_samples": len(retired["samples"]), "active_nonmusical_bindings": len(audio) - len(admitted)}))


if __name__ == "__main__":
    project()
