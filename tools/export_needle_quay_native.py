"""Blender background export of local sources to a native, upload-free demo.

Preserves source provenance; bounding primitives are presentation proxies, never
claimed to be native mesh imports or final approved art. Run with Blender.
"""
import bpy
import json
import hashlib
from pathlib import Path
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[1]
register = json.loads((ROOT / 'data/needle-quay-environment.v1.json').read_text(encoding='utf-8'))
result = []
for building in register['buildings']:
    source = ROOT / building['production_source']
    bpy.ops.wm.open_mainfile(filepath=str(source))
    parts = []
    for obj in bpy.context.scene.objects:
        if obj.type != 'MESH':
            continue
        bounds = [obj.matrix_world @ Vector(v) for v in obj.bound_box]
        low = [min(v[i] for v in bounds) for i in range(3)]
        high = [max(v[i] for v in bounds) for i in range(3)]
        center = [(low[i] + high[i]) / 2 for i in range(3)]
        size = [max(.04, high[i] - low[i]) for i in range(3)]
        rgb = list(obj.data.materials[0].diffuse_color[:3]) if obj.data.materials else [.5, .5, .5]
        parts.append({'name': obj.name, 'position': [round(center[i], 4) for i in (0, 2, 1)],
                      'size': [round(size[i], 4) for i in (0, 2, 1)],
                      'color': [round(c, 4) for c in rgb]})
    result.append({'id': building['id'], 'name': building['name'],
                   'center': building['blockout_center_xz_studs'],
                   'dimensions': building['blockout_dimensions_wdh_studs'],
                   'source': building['production_source'],
                   'sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'parts': parts})
payload = json.dumps(result, separators=(',', ':'))
(ROOT / 'src/shared/NeedleQuayGeometry.luau').write_text(
    '-- Generated by tools/export_needle_quay_native.py. Local native proxies, not mesh imports.\n'
    'return game:GetService("HttpService"):JSONDecode([=[' + payload + ']=])\n', encoding='utf-8')
print('Exported', len(result), 'buildings;', sum(len(b['parts']) for b in result), 'native primitives')

npcs = []
for npc in register['npcs']:
    if npc['canonical_asset_id'] == 'H04':
        continue  # Runtime reuses the existing canonical H04 assembly.
    source = (ROOT / npc['production_model']).with_suffix('.blend')
    bpy.ops.wm.open_mainfile(filepath=str(source))
    parts = []
    for obj in bpy.context.scene.objects:
        if obj.type != 'MESH':
            continue
        bounds = [obj.matrix_world @ Vector(v) for v in obj.bound_box]
        low = [min(v[i] for v in bounds) for i in range(3)]
        high = [max(v[i] for v in bounds) for i in range(3)]
        rgb = list(obj.data.materials[0].diffuse_color[:3]) if obj.data.materials else [.5, .5, .5]
        parts.append({'name': obj.name, 'position': [round((low[i]+high[i])/2, 4) for i in (0,2,1)],
                      'size': [round(max(.04, high[i]-low[i]), 4) for i in (0,2,1)], 'color': list(rgb)})
    npcs.append({'name': npc['name'], 'source': str(source.relative_to(ROOT)).replace('\\','/'),
                 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'parts': parts})
(ROOT / 'src/shared/NeedleQuayCharacters.luau').write_text(
    '-- Local native NPC proxies exported from authored Blender sources; rig animation is not imported.\n'
    'return game:GetService("HttpService"):JSONDecode([=[' + json.dumps(npcs,separators=(',',':')) + ']=])\n', encoding='utf-8')
print('Exported', len(npcs), 'NPC presentation sources')
